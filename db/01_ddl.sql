-- ---------------------------------------------------------------------
-- Servicos parceiros: abrigo, refeicao, banho e atendimento (RF10)
-- Horarios em VARCHAR2(5) "HH:MM" (o Oracle nao possui tipo TIME).
-- Abertura = fechamento significa funcionamento 24 horas.
-- ---------------------------------------------------------------------
CREATE TABLE T_CIVIA_SERVICO (
    ID_SERVICO       NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY,
    NOME             VARCHAR2(100)  NOT NULL,
    TIPO             VARCHAR2(20)   NOT NULL,
    ENDERECO         VARCHAR2(200)  NOT NULL,
    LATITUDE         NUMBER(9,6)    NOT NULL,
    LONGITUDE        NUMBER(9,6)    NOT NULL,
    HORA_ABERTURA    VARCHAR2(5)    NOT NULL,
    HORA_FECHAMENTO  VARCHAR2(5)    NOT NULL,
    APROVADO         NUMBER(1)      DEFAULT 0 NOT NULL,
    DATA_CADASTRO    TIMESTAMP      NOT NULL,
    CONSTRAINT PK_CIVIA_SERVICO PRIMARY KEY (ID_SERVICO),
    CONSTRAINT CK_CIVIA_SERVICO_TIPO CHECK (TIPO IN ('ABRIGO', 'REFEICAO', 'BANHO', 'ATENDIMENTO')),
    CONSTRAINT CK_CIVIA_SERVICO_APROVADO CHECK (APROVADO IN (0, 1)),
    CONSTRAINT CK_CIVIA_SERVICO_LAT CHECK (LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_CIVIA_SERVICO_LON CHECK (LONGITUDE BETWEEN -180 AND 180),
    CONSTRAINT CK_CIVIA_SERVICO_HR_ABRE CHECK (REGEXP_LIKE(HORA_ABERTURA, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_CIVIA_SERVICO_HR_FECHA CHECK (REGEXP_LIKE(HORA_FECHAMENTO, '^([01][0-9]|2[0-3]):[0-5][0-9]$'))
);

-- ---------------------------------------------------------------------
-- Perfis atendidos por servico (1 servico : N perfis) - usado no filtro de abrigo
-- ---------------------------------------------------------------------
CREATE TABLE T_CIVIA_SERVICO_PERFIL (
    ID_SERVICO  NUMBER(19)    NOT NULL,
    PERFIL      VARCHAR2(20)  NOT NULL,
    CONSTRAINT PK_CIVIA_SERVICO_PERFIL PRIMARY KEY (ID_SERVICO, PERFIL),
    CONSTRAINT FK_CIVIA_PERFIL_SERVICO FOREIGN KEY (ID_SERVICO)
        REFERENCES T_CIVIA_SERVICO (ID_SERVICO) ON DELETE CASCADE,
    CONSTRAINT CK_CIVIA_PERFIL CHECK (PERFIL IN ('HOMEM', 'MULHER', 'FAMILIA', 'LGBT', 'IDOSO', 'COM_ANIMAL'))
);

-- ---------------------------------------------------------------------
-- Totens instalados em pontos de grande circulacao
-- ---------------------------------------------------------------------
CREATE TABLE T_CIVIA_TOTEM (
    ID_TOTEM          NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY,
    IDENTIFICACAO     VARCHAR2(30)   NOT NULL,
    LOCAL_INSTALACAO  VARCHAR2(150)  NOT NULL,
    LATITUDE          NUMBER(9,6)    NOT NULL,
    LONGITUDE         NUMBER(9,6)    NOT NULL,
    ATIVO             NUMBER(1)      DEFAULT 1 NOT NULL,
    CONSTRAINT PK_CIVIA_TOTEM PRIMARY KEY (ID_TOTEM),
    CONSTRAINT UK_CIVIA_TOTEM_IDENTIFICACAO UNIQUE (IDENTIFICACAO),
    CONSTRAINT CK_CIVIA_TOTEM_ATIVO CHECK (ATIVO IN (0, 1)),
    CONSTRAINT CK_CIVIA_TOTEM_LAT CHECK (LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_CIVIA_TOTEM_LON CHECK (LONGITUDE BETWEEN -180 AND 180)
);

-- ---------------------------------------------------------------------
-- Atualizacoes de disponibilidade (painel das equipes, RF09)
-- Abrigo: VAGAS preenchido e SITUACAO nula. Demais tipos: SITUACAO preenchida e VAGAS nula
-- (regra validada na camada BO/dominio, pois depende do tipo do servico).
-- ---------------------------------------------------------------------
CREATE TABLE T_CIVIA_ATUALIZACAO_DISP (
    ID_ATUALIZACAO  NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    ID_SERVICO      NUMBER(19)    NOT NULL,
    VAGAS           NUMBER(5),
    SITUACAO        VARCHAR2(20),
    DATA_HORA       TIMESTAMP     NOT NULL,
    CONSTRAINT PK_CIVIA_ATUALIZACAO_DISP PRIMARY KEY (ID_ATUALIZACAO),
    CONSTRAINT FK_CIVIA_ATUALIZACAO_SERVICO FOREIGN KEY (ID_SERVICO)
        REFERENCES T_CIVIA_SERVICO (ID_SERVICO) ON DELETE CASCADE,
    CONSTRAINT CK_CIVIA_ATUALIZACAO_VAGAS CHECK (VAGAS IS NULL OR VAGAS >= 0),
    CONSTRAINT CK_CIVIA_ATUALIZACAO_SITUACAO CHECK (SITUACAO IS NULL OR SITUACAO IN ('ABERTO', 'FILA_GRANDE', 'LOTADO', 'FECHADO')),
    CONSTRAINT CK_CIVIA_ATUALIZACAO_DADO CHECK (VAGAS IS NOT NULL OR SITUACAO IS NOT NULL)
);

-- A consulta do totem busca a atualizacao mais recente de cada servico
CREATE INDEX IX_CIVIA_ATUALIZACAO_SERV_DATA ON T_CIVIA_ATUALIZACAO_DISP (ID_SERVICO, DATA_HORA);

COMMENT ON TABLE T_CIVIA_SERVICO IS 'Servicos parceiros exibidos nos totens (abrigo, refeicao, banho, atendimento)';
COMMENT ON TABLE T_CIVIA_SERVICO_PERFIL IS 'Perfis de publico atendidos por cada servico';
COMMENT ON TABLE T_CIVIA_TOTEM IS 'Totens de consulta instalados em pontos de grande circulacao';
COMMENT ON TABLE T_CIVIA_ATUALIZACAO_DISP IS 'Historico de atualizacoes de disponibilidade dos servicos';
